const { test, expect } = require('@playwright/test');
const BASE_URL = process.env.BASE_URL || 'http://localhost:5180';
test.use({ storageState: { cookies: [], origins: [] } });
test.skip(!['localhost', '127.0.0.1'].includes(new URL(BASE_URL).hostname), 'Local Generic 2.0 layout regression');

test('compact Generic Leads preserves scrolling alongside a selected-lead detail panel', async ({ page, request }) => {
  const response = await request.post(`${BASE_URL}/api/auth/login`, { data: { email: 'admin@globussoft.com', password: 'password123' } });
  expect(response.ok()).toBe(true);
  const { token, user, tenant } = await response.json();
  expect(tenant.vertical).toBe('generic');
  await page.addInitScript(({ token, user, tenant }) => {
    sessionStorage.setItem('token', token);
    localStorage.setItem('user', JSON.stringify(user));
    localStorage.setItem('tenant', JSON.stringify(tenant));
    localStorage.setItem('globuscrm.leads.tableDensity.v1', 'comfortable');
  }, { token, user, tenant });
  await page.route('**/api/tours/state', route => route.fulfill({ json: { preferences: { enabled: false, autoStart: false }, progress: {} } }));
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto(`${BASE_URL}/dashboard`);
  await expect(page.locator('h1').filter({ hasText: 'Enterprise Overview' })).toBeVisible();
  const skipTours = page.getByRole('button', { name: 'Skip all', exact: true });
  if (await skipTours.isVisible()) await skipTours.click();
  await expect(page.locator('.workspace-loading-overlay')).toHaveCount(0);
  await page.goto(`${BASE_URL}/leads`);
  const table = page.locator('.leads-split-table');
  await expect(table).toHaveClass(/density-compact/);
  await expect(page.getByRole('button', { name: /Table density/i })).toHaveCount(0);
  await expect(page.locator('.leads-page-root')).toHaveClass(/leads-page-root--analyst/);
  expect(await page.locator('.leads-toolbar-shell').evaluate(element => getComputedStyle(element).paddingTop)).toBe('8px');
  expect(await page.locator('#leads-secondary-actions').evaluate(element => getComputedStyle(element).display)).toBe('contents');
  const first = table.locator('.leads-table--frozen tbody tr').first();
  const name = first.locator('a').first();
  await expect(name).toBeVisible();
  const copyName = first.getByRole('button', { name: 'Copy Name', exact: true });
  await page.mouse.move(1, 1);
  await expect(copyName).toHaveCSS('opacity', '0');
  await name.hover();
  await expect(copyName).toHaveCSS('opacity', '1');
  const editName = first.getByRole('button', { name: /^Edit Name for / });
  const textBox = await name.boundingBox();
  const editBox = await editName.boundingBox();
  expect(editBox.x - (textBox.x + textBox.width)).toBeLessThan(16);
  const namePaneWidth = await page.locator('.leads-table-frozen-pane').evaluate(element => element.getBoundingClientRect().width);
  expect(namePaneWidth).toBeLessThan(200);
  const editEnd = editBox.x + editBox.width;
  const copyBox = await copyName.boundingBox();
  expect(copyBox.x - editEnd).toBeLessThan(12);
  await copyName.focus();
  await page.mouse.move(1, 1);
  await expect(copyName).toHaveCSS('opacity', '1');
  const leadName = await name.textContent();
  await name.click();
  const panel = page.getByRole('complementary', { name: 'Selected lead details' });
  await expect(panel).toBeVisible();
  await expect(panel.getByRole('heading', { name: leadName.trim(), exact: true })).toBeVisible();
  const tableBox = await table.boundingBox();
  const panelBox = await panel.boundingBox();
  expect(panelBox.x).toBeGreaterThanOrEqual(tableBox.x + tableBox.width);
  expect(panelBox.height).toBeLessThan(480);
  expect(await panel.locator('dl > div').first().evaluate(element => getComputedStyle(element).display)).toBe('grid');
  const frozenHeight = await first.evaluate(row => row.getBoundingClientRect().height);
  const scrollingHeight = await table.locator('.leads-table--scrollable tbody tr').first().evaluate(row => row.getBoundingClientRect().height);
  expect(Math.abs(frozenHeight - scrollingHeight)).toBeLessThan(2);
  expect(frozenHeight).toBeLessThanOrEqual(36);
  const lastRowBox = await table.locator('.leads-table--frozen tbody tr').last().boundingBox();
  const footerBox = await page.locator('.leads-pagination-footer').boundingBox();
  // Short result sets must not grow to fill the viewport below their rows.
  expect(footerBox.y - (lastRowBox.y + lastRowBox.height)).toBeLessThan(32);
  const cells = table.locator('.leads-table--frozen tbody tr td:first-child');
  expect(await cells.first().evaluate(cell => getComputedStyle(cell).paddingTop)).toBe('0px');
  expect(await cells.nth(1).evaluate(cell => getComputedStyle(cell).backgroundColor))
    .not.toBe(await cells.nth(2).evaluate(cell => getComputedStyle(cell).backgroundColor));
  const bar = table.locator('.top-scroll-sync__sticky-bottom');
  await first.hover();
  await page.mouse.wheel(220, 0);
  await expect.poll(() => bar.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
  await page.mouse.wheel(-10000, 0);
  await expect.poll(() => bar.evaluate(element => element.scrollLeft)).toBe(0);
  await page.screenshot({ path: '/tmp/generic-leads-dense-detail-desktop.png', fullPage: true });
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'));
  await expect(cells.nth(1)).toHaveCSS('background-color', 'rgb(25, 37, 54)');
  await expect(cells.nth(2)).toHaveCSS('background-color', 'rgb(14, 22, 34)');
  await page.screenshot({ path: '/tmp/generic-leads-ultra-dense-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(panel).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/generic-leads-dense-detail-mobile.png', fullPage: true });
  await panel.getByRole('button', { name: 'Close lead preview' }).click();
  await expect(panel).toHaveCount(0);
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.getByRole('button', { name: 'Call settings', exact: true }).click();
  const settings = page.getByRole('dialog', { name: 'Call settings', exact: true });
  await expect(settings).toHaveClass(/call-settings-dialog--dense/);
  const numeric = settings.locator('input[type="number"]').first();
  if (await numeric.isVisible()) await expect(numeric).toHaveCSS('height', '28px');
  await page.screenshot({ path: '/tmp/generic-call-settings-dense.png', fullPage: true });
  await settings.getByRole('button', { name: 'Cancel', exact: true }).click();
  await name.click();
  await expect(panel).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Copy lead name' })).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Copy lead company' })).toBeVisible();
  await panel.getByRole('button', { name: 'Close lead preview' }).click();
  await expect(page.locator('.generic-lead-detail-panel--closing')).toHaveAttribute('aria-hidden', 'true');
  await expect(page.locator('.generic-lead-detail-panel')).toHaveCount(0);
  await page.goto(`${BASE_URL}/contacts`);
  const contactsTable = page.locator('.contacts-split-table table.stable-table').first();
  await expect(contactsTable).toBeVisible();
  const contactCell = contactsTable.locator('tbody tr td').first();
  await expect(contactCell).toHaveCSS('padding-top', '3px');
  await expect.poll(async () => page.locator('.contacts-split-table').evaluate(surface => {
    const tables = surface.querySelectorAll('table.stable-table');
    const left = [...tables[0].querySelectorAll('tbody tr')];
    const right = [...tables[1].querySelectorAll('tbody tr')];
    return left.every((row, index) => Math.abs(row.getBoundingClientRect().top - right[index].getBoundingClientRect().top) < 2);
  })).toBe(true);
  await page.screenshot({ path: '/tmp/generic-contacts-dense.png', fullPage: true });
  for (const route of ['/invoices', '/payments', '/expenses', '/estimates', '/staff', '/converted-leads']) {
    await page.goto(`${BASE_URL}${route}`);
    const recordTable = page.locator('.app-shell--generic main table:is(.stable-table, .generic-record-dense, .staff-generic-resizable-table)').first();
    await expect(recordTable).toBeVisible();
    await expect(recordTable.locator('thead th').first()).toHaveCSS('padding-top', '3px');
  }
  // Browser zoom reduces the CSS viewport and activates the drawer layout.
  await page.setViewportSize({ width: 800, height: 900 });
  await page.getByRole('button', { name: 'Open navigation menu', exact: true }).click();
  const sidebar = page.locator('#app-sidebar');
  const leadGroup = sidebar.getByRole('button', { name: 'Leads', exact: true });
  await leadGroup.hover();
  await expect(leadGroup).toHaveAttribute('aria-expanded', 'true');
  await expect(sidebar.getByRole('menu', { name: 'Leads submodules' })).toBeVisible();
  await page.screenshot({ path: '/tmp/generic-sidebar-zoom-hover.png', fullPage: true });
});
