function normalizeHexColor(value, fallback = "#FFFFFF") {















  const text = String(value || "").trim();















  if (/^#[0-9a-fA-F]{6}$/.test(text)) return text.toUpperCase();















  if (/^[0-9a-fA-F]{6}$/.test(text)) return `#${text.toUpperCase()}`;















  return fallback;















}































